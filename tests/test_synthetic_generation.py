def test_transaction_events_row_count_matches_authorization_plus_capture_plus_reversal(result):
    events = result["tables"]["transaction_events"]
    transactions = result["tables"]["transactions"]
    approved = sum(1 for t in transactions if t["status"] == "APPROVED")
    auth = sum(1 for e in events if e["event_type"] == "AUTHORIZATION")
    capture = sum(1 for e in events if e["event_type"] == "CAPTURE")
    reversal = sum(1 for e in events if e["event_type"] == "REVERSAL")
    assert auth == len(transactions)
    assert capture == approved
    assert auth + capture + reversal == len(events)


