# ---- lifecycle ordering / boundary cases ----


def test_every_transaction_has_exactly_one_authorization_event(result):
    events_by_txn: dict[str, list] = {}
    for e in result["tables"]["transaction_events"]:
        events_by_txn.setdefault(e["transaction_id"], []).append(e)
    for txn in result["tables"]["transactions"]:
        types = [e["event_type"] for e in events_by_txn[txn["transaction_id"]]]
        assert types.count("AUTHORIZATION") == 1
        assert types[0] == "AUTHORIZATION"


def test_declined_transactions_have_no_capture_no_settlement_no_reward(result):
    settled_txn_ids = {s["transaction_id"] for s in result["tables"]["settlements"]}
    rewarded_txn_ids = {r["transaction_id"] for r in result["tables"]["reward_events"]}
    events_by_txn: dict[str, list] = {}
    for e in result["tables"]["transaction_events"]:
        events_by_txn.setdefault(e["transaction_id"], []).append(e)

    declined = [t for t in result["tables"]["transactions"] if t["status"] == "DECLINED"]
    assert len(declined) > 0  # sanity: the boundary case actually occurs
    for txn in declined:
        assert txn["transaction_id"] not in settled_txn_ids
        assert txn["transaction_id"] not in rewarded_txn_ids
        types = [e["event_type"] for e in events_by_txn[txn["transaction_id"]]]
        assert "CAPTURE" not in types
        assert "REVERSAL" not in types
        assert txn["decline_reason"] is not None
        assert txn["auth_code"] is None


def test_reversal_only_occurs_after_a_capture_and_some_reversals_exist(result):
    events_by_txn: dict[str, list] = {}
    for e in result["tables"]["transaction_events"]:
        events_by_txn.setdefault(e["transaction_id"], []).append(e)
    reversal_txns = [tid for tid, evs in events_by_txn.items() if any(e["event_type"] == "REVERSAL" for e in evs)]
    assert len(reversal_txns) > 0  # sanity: the scenario actually occurs
    for tid in reversal_txns:
        evs = sorted(events_by_txn[tid], key=lambda e: e["event_timestamp"])
        types = [e["event_type"] for e in evs]
        assert types == ["AUTHORIZATION", "CAPTURE", "REVERSAL"]
        auth_ts = datetime.fromisoformat(evs[0]["event_timestamp"])
        capture_ts = datetime.fromisoformat(evs[1]["event_timestamp"])
        reversal_ts = datetime.fromisoformat(evs[2]["event_timestamp"])
        assert auth_ts <= capture_ts <= reversal_ts


